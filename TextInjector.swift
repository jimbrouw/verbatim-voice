import Cocoa
import ApplicationServices

class TextInjector {
    static let shared = TextInjector()
    
    // Transient pasteboard types to prevent clipboard history pollution
    // Raycast, Alfred, Paste, and Maccy check for these types to ignore items
    private let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    
    // MARK: - Primary Injection API
    
    /// Injects text into the active cursor position, trying direct AX first, then transient pasteboard
    func inject(text: String, targetElement: AXUIElement? = nil) {
        guard !text.isEmpty else { return }
        
        // 1. Try direct Accessibility insertion first (works in native AppKit text fields)
        if let element = targetElement, canUseAXInjection(on: element) {
            if injectDirectly(text, to: element) {
                print("✅ [TextInjector] Direct AX text injection succeeded")
                return
            }
        }
        
        // 2. Fall back to zero-pollution transient clipboard paste (universal across Chrome, VS Code, Slack, Notes, etc.)
        print("📋 [TextInjector] Injecting via zero-pollution transient pasteboard")
        injectViaPasteboard(text: text)
    }
    
    // MARK: - Direct Accessibility Caret Injection
    
    /// Checks if the focused element allows inserting text at the caret
    func canUseAXInjection(on element: AXUIElement) -> Bool {
        var settable: DarwinBoolean = false
        let status = AXUIElementIsAttributeSettable(element, kAXSelectedTextAttribute as CFString, &settable)
        return status == .success && settable.boolValue
    }
    
    /// Injects text directly at the caret without touching the clipboard
    func injectDirectly(_ text: String, to element: AXUIElement) -> Bool {
        let status = AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, text as CFTypeRef)
        return status == .success
    }
    
    // MARK: - Zero-Pollution Clipboard Pasting
    
    func injectViaPasteboard(text: String) {
        guard !text.isEmpty else { return }
        let pasteboard = NSPasteboard.general
        let savedItems = backupPasteboard(pasteboard)
        
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Mark as transient and autogenerated so clipboard managers ignore it
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: autoGeneratedType)
        
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        
        // Give pasteboard server 25ms to commit data before firing keystroke
        usleep(25_000)
        
        simulatePaste()
        
        // Restore user's previous clipboard after the target app has consumed the text
        if !savedItems.isEmpty {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) { [weak self] in
                self?.restorePasteboard(savedItems, to: pasteboard)
            }
        }
    }
    
    /// Simulates Cmd+V keyboard shortcut across Session and HID taps with AppleScript fallback
    func simulatePaste() {
        let src = CGEventSource(stateID: .hidSystemState)
        let cmdKey: CGKeyCode = 0x37 // 55: Command key
        let vKey: CGKeyCode = 0x09   // 9: 'V' key
        
        guard let cmdDown = CGEvent(keyboardEventSource: src, virtualKey: cmdKey, keyDown: true),
              let vDown = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: true),
              let vUp = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: false),
              let cmdUp = CGEvent(keyboardEventSource: src, virtualKey: cmdKey, keyDown: false) else {
            fallbackAppleScriptPaste()
            return
        }
        
        cmdDown.flags = .maskCommand
        vDown.flags = .maskCommand
        vUp.flags = .maskCommand
        cmdUp.flags = []
        
        // Post to both Session tap (active login session) and HID tap with 15ms key spacing
        cmdDown.post(tap: .cgSessionEventTap)
        cmdDown.post(tap: .cghidEventTap)
        usleep(15_000)
        
        vDown.post(tap: .cgSessionEventTap)
        vDown.post(tap: .cghidEventTap)
        usleep(15_000)
        
        vUp.post(tap: .cgSessionEventTap)
        vUp.post(tap: .cghidEventTap)
        usleep(15_000)
        
        cmdUp.post(tap: .cgSessionEventTap)
        cmdUp.post(tap: .cghidEventTap)
    }
    
    /// AppleScript fallback when synthetic CGEvents are intercepted or sandboxed
    private func fallbackAppleScriptPaste() {
        let script = "tell application \"System Events\" to keystroke \"v\" using command down"
        if let appleScript = NSAppleScript(source: script) {
            var error: NSDictionary?
            appleScript.executeAndReturnError(&error)
            if let error = error {
                print("⚠️ [TextInjector] AppleScript fallback paste failed: \(error)")
            }
        }
    }
    
    /// Synthesizes Return key press for spoken commands like "press enter"
    func postReturnKey() {
        let src = CGEventSource(stateID: .hidSystemState)
        let returnKeyCode: CGKeyCode = 0x24 // Return
        
        guard let keyDown = CGEvent(keyboardEventSource: src, virtualKey: returnKeyCode, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: src, virtualKey: returnKeyCode, keyDown: false) else {
            return
        }
        
        keyDown.flags = []
        keyUp.flags = []
        
        keyDown.post(tap: .cgSessionEventTap)
        keyDown.post(tap: .cghidEventTap)
        usleep(15_000)
        keyUp.post(tap: .cgSessionEventTap)
        keyUp.post(tap: .cghidEventTap)
    }
    
    // MARK: - Clipboard Preservation
    
    func backupPasteboard(_ pasteboard: NSPasteboard) -> [[(NSPasteboard.PasteboardType, Data)]] {
        guard let items = pasteboard.pasteboardItems else { return [] }
        return items.compactMap { item in
            let typesData = item.types.compactMap { type -> (NSPasteboard.PasteboardType, Data)? in
                if let data = item.data(forType: type) {
                    return (type, data)
                }
                return nil
            }
            return typesData.isEmpty ? nil : typesData
        }
    }
    
    func restorePasteboard(_ backup: [[(NSPasteboard.PasteboardType, Data)]], to pasteboard: NSPasteboard) {
        guard !backup.isEmpty else { return }
        pasteboard.clearContents()
        var objectsToWrite: [NSPasteboardItem] = []
        for itemData in backup {
            let pbItem = NSPasteboardItem()
            for (type, data) in itemData {
                pbItem.setData(data, forType: type)
            }
            objectsToWrite.append(pbItem)
        }
        pasteboard.writeObjects(objectsToWrite)
    }
    
    // MARK: - Word Tokenizer (Utility)
    
    func tokenizeIntoWords(text: String) -> [String] {
        var tokens: [String] = []
        var currentToken = ""
        var inWhitespace = false
        
        for char in text {
            if char.isWhitespace {
                currentToken.append(char)
                inWhitespace = true
            } else {
                if inWhitespace {
                    tokens.append(currentToken)
                    currentToken = ""
                    inWhitespace = false
                }
                currentToken.append(char)
            }
        }
        if !currentToken.isEmpty {
            tokens.append(currentToken)
        }
        return tokens
    }
}
